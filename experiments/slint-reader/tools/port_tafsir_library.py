PLATFORM = '''/// Whether the process that owns a staging folder may still be running.
/// Another running app can be writing a valid journal in this profile, so its
/// stage is preserved; an unknown answer counts as running.
#[cfg(unix)]
fn process_running(pid: u32) -> bool {
    let Ok(pid) = libc::pid_t::try_from(pid) else {
        return false;
    };
    // Signal 0 only asks. EPERM means the process exists under another user.
    let asked = unsafe { libc::kill(pid, 0) };
    asked == 0 || std::io::Error::last_os_error().raw_os_error() != Some(libc::ESRCH)
}
#[cfg(windows)]
fn process_running(pid: u32) -> bool {
    let mut process_ids = vec![0u32; 16_384];
    let mut process_bytes = 0;
    let capacity_bytes = (process_ids.len() * std::mem::size_of::<u32>()) as u32;
    if unsafe {
        windows::Win32::System::ProcessStatus::EnumProcesses(
            process_ids.as_mut_ptr(),
            capacity_bytes,
            &mut process_bytes,
        )
    }
    .is_err()
        || process_bytes >= capacity_bytes
        || process_bytes % 4 != 0
    {
        return true;
    }
    process_ids[..process_bytes as usize / 4].contains(&pid)
}
/// Renames `from` to `to` only if nothing is at `to`, in one step, so other
/// software or unknown files never become collateral of an installation.
fn rename_new(from: &Path, to: &Path) -> Result<()> {
    #[cfg(unix)]
    {
        use std::{ffi::CString, os::unix::ffi::OsStrExt};
        let from_c = CString::new(from.as_os_str().as_bytes())?;
        let to_c = CString::new(to.as_os_str().as_bytes())?;
        // None: this system has no exclusive rename (only Linux and macOS
        // are built), so the check-then-rename below is used.
        #[cfg(any(target_os = "linux", target_os = "android"))]
        let moved = Some(unsafe {
            libc::renameat2(
                libc::AT_FDCWD,
                from_c.as_ptr(),
                libc::AT_FDCWD,
                to_c.as_ptr(),
                libc::RENAME_NOREPLACE,
            )
        });
        #[cfg(target_vendor = "apple")]
        let moved =
            Some(unsafe { libc::renamex_np(from_c.as_ptr(), to_c.as_ptr(), libc::RENAME_EXCL) });
        #[cfg(not(any(target_os = "linux", target_os = "android", target_vendor = "apple")))]
        let moved: Option<i32> = None;
        if moved == Some(0) {
            return Ok(());
        }
        let error = std::io::Error::last_os_error();
        // A file system without exclusive rename (some network and FUSE
        // mounts): check, then rename. The target is inside this profile's
        // own tafsir folder, used under the library lock and the profile lock.
        let unsupported = moved.is_none()
            || matches!(
                error.raw_os_error(),
                Some(libc::EINVAL | libc::ENOSYS | libc::ENOTSUP)
            );
        if !unsupported {
            return Err(error.into());
        }
        match fs::symlink_metadata(to) {
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Ok(_) => return Err("Tafsir target already exists; it was preserved".into()),
            Err(e) => return Err(e.into()),
        }
        fs::rename(from, to)?;
        Ok(())
    }
    #[cfg(windows)]
    {
        use std::os::windows::ffi::OsStrExt;
        use windows::{Win32::Storage::FileSystem::MoveFileW, core::PCWSTR};
        let from: Vec<_> = from.as_os_str().encode_wide().chain(Some(0)).collect();
        let to: Vec<_> = to.as_os_str().encode_wide().chain(Some(0)).collect();
        unsafe {
            MoveFileW(PCWSTR(from.as_ptr()), PCWSTR(to.as_ptr()))?;
        }
        Ok(())
    }
}
/// Makes a rename durable, as MOVEFILE_WRITE_THROUGH did.
fn sync_parent(path: &Path) -> Result<()> {
    #[cfg(unix)]
    if let Some(parent) = path.parent() {
        File::open(parent)?.sync_all()?;
    }
    #[cfg(windows)]
    let _ = path;
    Ok(())
}
fn move_journal(from: &Path, to: &Path, replace: bool) -> Result<()> {
    if replace {
        fs::rename(from, to)?;
    } else {
        rename_new(from, to)?;
    }
    sync_parent(to)
}
fn move_new(from: &Path, to: &Path) -> Result<()> {
    rename_new(from, to)?;
    sync_parent(to)
}
'''

TRANSPORT = '''/// HTTPS to api.quran.com through ureq and rustls, with the WinHTTP
/// transport's rules: TLS only, no redirects, cookies or credentials, identity
/// encoding, 8-second network timeouts, 45 seconds per response.
struct HttpsTransport;
impl Transport for HttpsTransport {
    fn fetch(&self, request: Request, state: &JobState) -> Result<Vec<u8>> {
        let mut last = String::new();
        for attempt in 0..3 {
            state.check()?;
            match fetch_https(request, state) {
                Ok(bytes) => return Ok(bytes),
                Err(error) => last = error.to_string(),
            }
            state.check()?;
            if attempt < 2 {
                for _ in 0..(20 * (attempt + 1)) {
                    state.check()?;
                    thread::sleep(Duration::from_millis(50));
                }
            }
        }
        Err(format!(
            "Could not download tafsir {} after 3 attempts: {last}",
            request.path()?
        )
        .into())
    }
}
fn agent() -> &'static ureq::Agent {
    static AGENT: std::sync::OnceLock<ureq::Agent> = std::sync::OnceLock::new();
    AGENT.get_or_init(|| {
        ureq::Agent::config_builder()
            .https_only(true)
            .max_redirects(0)
            .http_status_as_error(false)
            .timeout_resolve(Some(Duration::from_secs(8)))
            .timeout_connect(Some(Duration::from_secs(8)))
            .timeout_send_request(Some(Duration::from_secs(8)))
            .timeout_recv_response(Some(Duration::from_secs(8)))
            .timeout_recv_body(Some(Duration::from_secs(45)))
            .user_agent("QuranMushafReader-Native/0.2")
            .build()
            .into()
    })
}
fn fetch_https(request: Request, state: &JobState) -> Result<Vec<u8>> {
    let url = format!("https://api.quran.com{}", request.path()?);
    let started = Instant::now();
    state.check()?;
    let mut response = agent()
        .get(&url)
        .header("Accept", "application/json")
        .header("Accept-Encoding", "identity")
        .call()
        .map_err(|error| format!("Quran.com tafsir provider could not be reached: {error}"))?;
    state.check()?;
    let header = |name: &str| -> Result<String> {
        Ok(match response.headers().get(name) {
            None => String::new(),
            Some(value) => value
                .to_str()
                .map_err(|_| "Invalid tafsir response header")?
                .to_owned(),
        })
    };
    let content_type = header("content-type")?;
    let encoding = header("content-encoding")?;
    let length = header("content-length")?;
    let status = u32::from(response.status().as_u16());
    let expected = response_headers(status, &content_type, &encoding, &length)?;
    let mut reader = response
        .body_mut()
        .with_config()
        .limit(RESPONSE_LIMIT as u64 + 1)
        .reader();
    let mut bytes = Vec::with_capacity(expected.unwrap_or(32 * 1024) as usize);
    let mut buffer = [0u8; 32 * 1024];
    loop {
        state.check()?;
        if started.elapsed() > Duration::from_secs(45) {
            return Err("Tafsir download exceeded its time limit".into());
        }
        let count = reader.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        if bytes.len() + count > RESPONSE_LIMIT {
            return Err("Tafsir response grew beyond its size limit".into());
        }
        bytes.extend_from_slice(&buffer[..count]);
    }
    state.check()?;
    if bytes.is_empty() || expected.is_some_and(|n| n != bytes.len() as u64) {
        return Err("Tafsir response is empty or incomplete".into());
    }
    Ok(bytes)
}
'''

