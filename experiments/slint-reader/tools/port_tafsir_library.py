"""Generates src/portable/tafsir_library.rs from the native Windows one.

    python tools/port_tafsir_library.py

The tafsir library (download, verify, publish, recover and read complete
tafsir books) is the native file word for word, except for its Windows calls:
WinHTTP, the reparse-point checks, EnumProcesses and MoveFile. Each is
replaced below by exact text; if the native file changes so that a replacement
no longer matches, this script stops instead of guessing. The output records
the native file's SHA-256, and a test fails when the native file has changed
since, so the copy is regenerated rather than left to drift.
"""
